// pkgFile is one file installed by a package.
type pkgFile struct {
	Path string // absolute target path, e.g. /usr/bin/olcwrt
	Mode int64
	Data []byte
}

// pkgSpec describes an OpenWrt package independent of its format.
type pkgSpec struct {
	Name        string
	Version     string
	Arch        string // OpenWrt arch, or "all"
	Depends     []string
	Section     string
	Description string
	License     string
	URL         string
	Maintainer  string
	Files       []pkgFile
	Conffiles   []string
	PostinstPkg string // package specific part, appended to default_postinst
	PrermPkg    string // package specific part, run before default_prerm
}

func (p *pkgSpec) installedSize() int64 {
	var n int64
	for _, f := range p.Files {
		n += int64(len(f.Data))
	}
	return n
}

func (p *pkgSpec) sortedFiles() []pkgFile {
	files := append([]pkgFile(nil), p.Files...)
	sort.Slice(files, func(i, j int) bool { return files[i].Path < files[j].Path })
	return files
}

// tarBuilder writes deterministic tar archives owned by root.
type tarBuilder struct {
	buf   bytes.Buffer
	tw    *tar.Writer
	mtime time.Time
	dirs  map[string]bool
}

func newTar(mtime time.Time) *tarBuilder {
	t := &tarBuilder{mtime: mtime, dirs: map[string]bool{}}
	t.tw = tar.NewWriter(&t.buf)
	return t
}

func (t *tarBuilder) header(name string, mode int64, typ byte, size int64) *tar.Header {
	return &tar.Header{
		Name: name, Mode: mode, Typeflag: typ, Size: size, ModTime: t.mtime,
		Uname: "root", Gname: "root", Format: tar.FormatGNU,
	}
}

func (t *tarBuilder) dir(name string) error {
	if t.dirs[name] {
		return nil
	}
	if name == "." {
		t.dirs[name] = true
		return t.tw.WriteHeader(t.header("./", 0o755, tar.TypeDir, 0))
	}
	if err := t.dir(path.Dir(name)); err != nil {
		return err
	}
	t.dirs[name] = true
	return t.tw.WriteHeader(t.header("./"+name+"/", 0o755, tar.TypeDir, 0))
}

func (t *tarBuilder) file(name string, mode int64, data []byte) error {
	name = strings.TrimPrefix(path.Clean("/"+name), "/")
	if err := t.dir(path.Dir(name)); err != nil {
		return err
	}
	if err := t.tw.WriteHeader(t.header("./"+name, mode, tar.TypeReg, int64(len(data)))); err != nil {
		return err
	}
	_, err := t.tw.Write(data)
	return err
}

func (t *tarBuilder) bytes() ([]byte, error) {
	if err := t.tw.Close(); err != nil {
		return nil, err
	}
	return t.buf.Bytes(), nil
}

func gzipBytes(data []byte) ([]byte, error) {
	var b bytes.Buffer
	zw, err := gzip.NewWriterLevel(&b, gzip.BestCompression)
	if err != nil {
		return nil, err
	}
	if _, err := zw.Write(data); err != nil {
		return nil, err
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// Scripts identical to the wrappers generated by OpenWrt's package-pack.mk.
const (
	ipkPostinst = "#!/bin/sh\n[ \"${IPKG_NO_SCRIPT}\" = \"1\" ] && exit 0\n[ -s ${IPKG_INSTROOT}/lib/functions.sh ] || exit 0\n. ${IPKG_INSTROOT}/lib/functions.sh\ndefault_postinst $0 $@\n"
	ipkPrerm    = "#!/bin/sh\n[ -s ${IPKG_INSTROOT}/lib/functions.sh ] || exit 0\n. ${IPKG_INSTROOT}/lib/functions.sh\ndefault_prerm $0 $@\n"
)

func (p *pkgSpec) controlText() string {
	var b strings.Builder
	fmt.Fprintf(&b, "Package: %s\nVersion: %s\n", p.Name, p.Version)
	if len(p.Depends) > 0 {
		fmt.Fprintf(&b, "Depends: %s\n", strings.Join(p.Depends, ", "))
	}
	fmt.Fprintf(&b, "License: %s\nSection: %s\nURL: %s\nMaintainer: %s\nArchitecture: %s\nInstalled-Size: %d\n",
		p.License, p.Section, p.URL, p.Maintainer, p.Arch, p.installedSize())
	fmt.Fprintf(&b, "Description:  %s\n", p.Description)
	return b.String()
}

// writeIPK creates an opkg package (gzip tar of debian-binary, data and control).
func writeIPK(p *pkgSpec, dir string, mtime time.Time) (string, error) {
	data := newTar(mtime)
	for _, f := range p.sortedFiles() {
		if err := data.file(f.Path, f.Mode, f.Data); err != nil {
			return "", err
		}
	}
	dataTar, err := data.bytes()
	if err != nil {
		return "", err
	}

	ctrl := newTar(mtime)
	ctrlFiles := []struct {
		name string
		mode int64
		body string
	}{
		{"control", 0o644, p.controlText()},
		{"postinst", 0o755, ipkPostinst},
		{"prerm", 0o755, ipkPrerm},
	}
	if len(p.Conffiles) > 0 {
		ctrlFiles = append(ctrlFiles, struct {
			name string
			mode int64
			body string
		}{"conffiles", 0o644, strings.Join(p.Conffiles, "\n") + "\n"})
	}
	if p.PostinstPkg != "" {
		ctrlFiles = append(ctrlFiles, struct {
			name string
			mode int64
			body string
		}{"postinst-pkg", 0o755, p.PostinstPkg})
	}
	if p.PrermPkg != "" {
		ctrlFiles = append(ctrlFiles, struct {
			name string
			mode int64
			body string
		}{"prerm-pkg", 0o755, p.PrermPkg})
	}
	for _, f := range ctrlFiles {
		if err := ctrl.file(f.name, f.mode, []byte(f.body)); err != nil {
			return "", err
		}
	}
	ctrlTar, err := ctrl.bytes()
	if err != nil {
		return "", err
	}

	dataGz, err := gzipBytes(dataTar)
	if err != nil {
		return "", err
	}
	ctrlGz, err := gzipBytes(ctrlTar)
	if err != nil {
		return "", err
	}
	outer := newTar(mtime)
	outer.dirs["."] = true
	for _, part := range []struct {
		name string
		data []byte
	}{{"debian-binary", []byte("2.0\n")}, {"data.tar.gz", dataGz}, {"control.tar.gz", ctrlGz}} {
		if err := outer.tw.WriteHeader(outer.header("./"+part.name, 0o644, tar.TypeReg, int64(len(part.data)))); err != nil {
			return "", err
		}
		if _, err := outer.tw.Write(part.data); err != nil {
			return "", err
		}
	}
	outerTar, err := outer.bytes()
	if err != nil {
		return "", err
	}
	ipk, err := gzipBytes(outerTar)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	out := filepath.Join(dir, fmt.Sprintf("%s_%s_%s.ipk", p.Name, p.Version, p.Arch))
	return out, os.WriteFile(out, ipk, 0o644)
}

// apkStage builds the input of `apk mkpkg`: a tar with the package files,
// the metadata files OpenWrt keeps under /lib/apk/packages, and the scripts.
func apkStage(p *pkgSpec, mtime time.Time) ([]byte, error) {
	t := newTar(mtime)
	var list []string
	for _, f := range p.sortedFiles() {
		if err := t.file("files"+f.Path, f.Mode, f.Data); err != nil {
			return nil, err
		}
		list = append(list, f.Path)
	}
	meta := "files/lib/apk/packages/" + p.Name
	metaFiles := map[string]string{}
	if len(p.Conffiles) > 0 {
		var static strings.Builder
		for _, c := range p.Conffiles {
			for _, f := range p.Files {
				if f.Path == c {
					sum := sha256.Sum256(f.Data)
					fmt.Fprintf(&static, "%s %s\n", c, hex.EncodeToString(sum[:]))
				}
			}
		}
		metaFiles[meta+".conffiles"] = strings.Join(p.Conffiles, "\n") + "\n"
		metaFiles[meta+".conffiles_static"] = static.String()
		list = append(list, "/lib/apk/packages/"+p.Name+".conffiles", "/lib/apk/packages/"+p.Name+".conffiles_static")
	}
	list = append(list, "/lib/apk/packages/"+p.Name+".list")
	sort.Strings(list)
	metaFiles[meta+".list"] = strings.Join(list, "\n") + "\n"

	postInstall := "#!/bin/sh\n[ \"${IPKG_NO_SCRIPT}\" = \"1\" ] && exit 0\n[ -s ${IPKG_INSTROOT}/lib/functions.sh ] || exit 0\n" +
		". ${IPKG_INSTROOT}/lib/functions.sh\nexport root=\"${IPKG_INSTROOT}\"\nexport pkgname=\"" + p.Name + "\"\n" +
		"add_group_and_user\ndefault_postinst\n" + stripShebang(p.PostinstPkg)
	preDeinstall := "#!/bin/sh\n[ -s ${IPKG_INSTROOT}/lib/functions.sh ] || exit 0\n. ${IPKG_INSTROOT}/lib/functions.sh\n" +
		"export root=\"${IPKG_INSTROOT}\"\nexport pkgname=\"" + p.Name + "\"\ndefault_prerm\n" + stripShebang(p.PrermPkg)
	metaFiles["scripts/post-install"] = postInstall
	metaFiles["scripts/post-upgrade"] = "#!/bin/sh\nexport PKG_UPGRADE=1\n" + stripShebang(postInstall)
	metaFiles["scripts/pre-deinstall"] = preDeinstall

	names := make([]string, 0, len(metaFiles))
	for n := range metaFiles {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		mode := int64(0o644)
		if strings.HasPrefix(n, "scripts/") {
			mode = 0o755
		}
		if err := t.file(n, mode, []byte(metaFiles[n])); err != nil {
			return nil, err
		}
	}
	return t.bytes()
}

func stripShebang(s string) string {
	if strings.HasPrefix(s, "#!") {
		if i := strings.IndexByte(s, '\n'); i >= 0 {
			return s[i+1:]
		}
		return ""
	}
	return s
}

// apkMkpkgArgs are the `apk mkpkg` arguments, relative to the stage dir.
func (p *pkgSpec) apkMkpkgArgs(output string) []string {
	arch := p.Arch
	if arch == "all" {
		arch = "noarch"
	}
	return []string{
		"mkpkg",
		"--info", "name:" + p.Name,
		"--info", "version:" + p.Version,
		"--info", "description:" + p.Description,
		"--info", "arch:" + arch,
		"--info", "license:" + p.License,
		"--info", "origin:" + p.Name,
		"--info", "url:" + p.URL,
		"--info", "maintainer:" + p.Maintainer,
		"--script", "post-install:scripts/post-install",
		"--script", "post-upgrade:scripts/post-upgrade",
		"--script", "pre-deinstall:scripts/pre-deinstall",
		"--info", "depends:" + strings.Join(p.Depends, " "),
		"--files", "files",
		"--output", output,
	}
}
