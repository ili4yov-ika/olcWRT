package main

import (
	"fmt"
	"strconv"
	"strings"
)

// yamlQuote renders a single-quoted YAML scalar.
func yamlQuote(v string) string {
	return "'" + strings.ReplaceAll(v, "'", "''") + "'"
}

type yamlWriter struct {
	b strings.Builder
}

func (w *yamlWriter) line(indent int, format string, args ...any) {
	w.b.WriteString(strings.Repeat("  ", indent))
	fmt.Fprintf(&w.b, format, args...)
	w.b.WriteByte('\n')
}

// olcrtcParams are the process-wide values that do not depend on a server.
type olcrtcParams struct {
	DNS       string
	SocksHost string
	SocksPort int
	SocksUser string
	SocksPass string
	Debug     bool
	Retry     string
}

// buildOlcrtcYAML renders an olcrtc client configuration. A single server is
// written flat; several servers become failover profiles tried in order.
func buildOlcrtcYAML(p olcrtcParams, servers []*Server) string {
	w := &yamlWriter{}
	w.line(0, "# generated by olcwrt %s - do not edit, changes are overwritten", version)
	w.line(0, "mode: cnc")
	if p.Debug {
		w.line(0, "debug: true")
	}
	w.line(0, "socks:")
	w.line(1, "host: %s", yamlQuote(p.SocksHost))
	w.line(1, "port: %d", p.SocksPort)
	if p.SocksUser != "" && p.SocksPass != "" {
		w.line(1, "user: %s", yamlQuote(p.SocksUser))
		w.line(1, "pass: %s", yamlQuote(p.SocksPass))
	}

	if len(servers) == 1 {
		writeServerYAML(w, 0, servers[0], p.DNS)
		return w.b.String()
	}

	w.line(0, "net:")
	w.line(1, "dns: %s", yamlQuote(p.DNS))
	w.line(0, "profiles:")
	for _, s := range servers {
		w.line(1, "- name: %s", yamlQuote(s.ID))
		writeServerYAML(w, 2, s, "")
	}
	w.line(0, "failover:")
	w.line(1, "retry_delay: %s", yamlQuote(p.Retry))
	w.line(1, "max_cycles: 0")
	return w.b.String()
}

func writeServerYAML(w *yamlWriter, ind int, s *Server, dns string) {
	w.line(ind, "auth:")
	w.line(ind+1, "provider: %s", yamlQuote(s.Provider))
	if s.Token != "" {
		w.line(ind+1, "token: %s", yamlQuote(s.Token))
	}
	w.line(ind, "room:")
	w.line(ind+1, "id: %s", yamlQuote(s.Room))
	if s.Channel != "" {
		w.line(ind+1, "channel: %s", yamlQuote(s.Channel))
	}
	w.line(ind, "crypto:")
	w.line(ind+1, "key: %s", yamlQuote(s.Key))
	w.line(ind, "net:")
	w.line(ind+1, "transport: %s", yamlQuote(s.Transport))
	if dns != "" {
		w.line(ind+1, "dns: %s", yamlQuote(dns))
	}

	section := ""
	for _, o := range transportOptsFor(s.Transport) {
		v := s.Opts[o.uci]
		if v == "" {
			continue
		}
		if o.section != section {
			w.line(ind, "%s:", o.section)
			section = o.section
		}
		if o.kind == optInt {
			if n, err := strconv.Atoi(v); err == nil {
				w.line(ind+1, "%s: %d", o.field, n)
			}
			continue
		}
		w.line(ind+1, "%s: %s", o.field, yamlQuote(v))
	}
}
