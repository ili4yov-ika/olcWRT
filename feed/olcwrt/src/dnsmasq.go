// The conf-dir snippet only points dnsmasq at a servers file, which dnsmasq
// re-reads on SIGHUP. Domain list changes therefore need no restart; only
// adding or removing the snippet (and no-resolv) does. The servers file lives
// in the conf-dir because that directory is mounted into dnsmasq's jail; the
// leading dot keeps conf-dir from parsing it as a regular config file.
const (
	dnsmasqConfName    = "olcwrt.conf"
	dnsmasqServersName = ".olcwrt.servers"
)

// dnsmasqInstance is one dnsmasq section of /etc/config/dhcp.
type dnsmasqInstance struct {
	Name     string
	ConfDir  string
	Servers  []string
	NoResolv bool
}

func dnsmasqInstances() []dnsmasqInstance {
	pkg, err := loadUCI("dhcp")
	if err != nil {
		return nil
	}
	var out []dnsmasqInstance
	for _, s := range pkg.OfType("dnsmasq") {
		dir := s.GetDef("confdir", "/tmp/dnsmasq."+s.Name+".d")
		dir = strings.SplitN(dir, ",", 2)[0]
		if !strings.HasPrefix(dir, "/") {
			continue
		}
		out = append(out, dnsmasqInstance{
			Name:     s.Name,
			ConfDir:  dir,
			Servers:  s.List("server"),
			NoResolv: s.Bool("noresolv", false),
		})
	}
	return out
}

// dnsmasqPlan is what olcwrt wants dnsmasq to do.
type dnsmasqPlan struct {
	Active  bool
	All     bool // forward every query to olcwrt (no-resolv)
	Port    int
	Domains []string
}

// snippet renders the conf-dir file for an instance conf-dir.
func (p dnsmasqPlan) snippet(confDir string) string {
	if !p.Active {
		return ""
	}
	s := "# generated by olcwrt - do not edit\nservers-file=" + filepath.Join(confDir, dnsmasqServersName) + "\n"
	if p.All {
		s += "no-resolv\n"
	}
	return s
}

// servers renders the servers file. With All every query is forwarded to
// the olcwrt resolver; otherwise only the listed domains are.
func (p dnsmasqPlan) servers() string {
	if !p.Active {
		return ""
	}
	var b strings.Builder
	target := "127.0.0.1#" + strconv.Itoa(p.Port)
	if p.All {
		b.WriteString("server=" + target + "\n")
	}
	for _, d := range p.Domains {
		b.WriteString("server=/" + d + "/" + target + "\n")
	}
	return b.String()
}

// dnsmasqWarnings reports settings that make dnsmasq bypass olcwrt.
func dnsmasqWarnings(insts []dnsmasqInstance, all bool) []string {
	if len(insts) == 0 {
		return []string{"no dnsmasq instance found, DNS integration disabled"}
	}
	if !all {
		return nil
	}
	var warnings []string
	for _, in := range insts {
		for _, srv := range in.Servers {
			if !strings.HasPrefix(srv, "/") {
				warnings = append(warnings, fmt.Sprintf(
					"dnsmasq %s forwards to %s as well (dhcp server option); DNS may bypass the tunnel", in.Name, srv))
			}
		}
	}
	return warnings
}

// applyDnsmasqPlan writes the snippet and servers file of every instance.
// It reports whether dnsmasq must be restarted (the snippet changed); other
// changes only need a SIGHUP.
func applyDnsmasqPlan(insts []dnsmasqInstance, p dnsmasqPlan) (restart bool, err error) {
	for _, in := range insts {
		servers := filepath.Join(in.ConfDir, dnsmasqServersName)
		if p.Active {
			if err := os.MkdirAll(in.ConfDir, 0o755); err != nil {
				return restart, err
			}
			// Write the servers file first so a restarted dnsmasq finds it.
			if _, err := syncFile(servers, p.servers()); err != nil {
				return restart, err
			}
		}
		changed, err := syncFile(filepath.Join(in.ConfDir, dnsmasqConfName), p.snippet(in.ConfDir))
		if err != nil {
			return restart, err
		}
		restart = restart || changed
		if !p.Active {
			_ = os.Remove(servers)
		}
	}
	return restart, nil
}

// syncFile makes path hold content (removing it for empty content) and
// reports whether it changed.
func syncFile(path, content string) (bool, error) {
	old, err := os.ReadFile(path)
	exists := err == nil
	if content == "" {
		if !exists {
			return false, nil
		}
		return true, os.Remove(path)
	}
	if exists && bytes.Equal(old, []byte(content)) {
		return false, nil
	}
	return true, writeFileAtomic(path, []byte(content), 0o644)
}

// removeDnsmasqConf deletes snippets from all known and default locations
// and reports whether dnsmasq must be restarted.
func removeDnsmasqConf() bool {
	restart, _ := applyDnsmasqPlan(dnsmasqInstances(), dnsmasqPlan{})
	for _, name := range []string{dnsmasqConfName, dnsmasqServersName} {
		matches, _ := filepath.Glob("/tmp/dnsmasq*.d/" + name)
		for _, m := range matches {
			if os.Remove(m) == nil && name == dnsmasqConfName {
				restart = true
			}
		}
	}
	return restart
}

func restartDnsmasq() error {
	const initScript = "/etc/init.d/dnsmasq"
	if _, err := os.Stat(initScript); err != nil {
		return nil
	}
	cmd := exec.Command(initScript, "restart")
	out, err := runWithTimeout(cmd, 30*time.Second)
	if err != nil {
		return fmt.Errorf("dnsmasq restart: %w: %s", err, strings.TrimSpace(string(out)))
	}
	return nil
}

// flushDnsmasqCache sends SIGHUP so dnsmasq forgets cached answers whose
// addresses are no longer present in the nft sets.
func flushDnsmasqCache() {
	for _, pid := range findProcesses("dnsmasq") {
		_ = signalPID(pid, syscall.SIGHUP)
	}
}

// findProcesses returns the PIDs whose comm matches name.
func findProcesses(name string) []int {
	entries, err := os.ReadDir("/proc")
	if err != nil {
		return nil
	}
	var pids []int
	for _, e := range entries {
		pid, err := strconv.Atoi(e.Name())
		if err != nil {
			continue
		}
		comm, err := os.ReadFile(filepath.Join("/proc", e.Name(), "comm"))
		if err == nil && strings.TrimSpace(string(comm)) == name {
			pids = append(pids, pid)
		}
	}
	return pids
}

// systemResolvers returns the upstream DNS servers learned from the WAN,
// in host:port form.
func systemResolvers() []string {
	var out []string
	for _, path := range []string{"/tmp/resolv.conf.d/resolv.conf.auto", "/tmp/resolv.conf.auto"} {
		data, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		for _, line := range strings.Split(string(data), "\n") {
			f := strings.Fields(line)
			if len(f) < 2 || f[0] != "nameserver" {
				continue
			}
			ip := f[1]
			if i := strings.IndexByte(ip, '%'); i >= 0 {
				continue // link-local with zone, not usable as plain host:port
			}
			if strings.HasPrefix(ip, "127.") || ip == "::1" {
				continue
			}
			if hp, err := normalizeHostPort(ip, 53); err == nil && !contains(out, hp) {
				out = append(out, hp)
			}
		}
		if len(out) > 0 {
			break
		}
	}
	return out
}
